import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const docsDir = path.join(rootDir, 'youthnic-ai-studio-docs');
const outputDataFile = path.join(rootDir, 'src', 'features', 'docs', 'docsData.ts');
const publicImagesDir = path.join(rootDir, 'public', 'images');
const sourceImagesDir = path.join(docsDir, 'images');

const outputDataDir = path.dirname(outputDataFile);
if (!fs.existsSync(outputDataDir)) {
  fs.mkdirSync(outputDataDir, { recursive: true });
}


if (fs.existsSync(sourceImagesDir)) {
  const images = fs.readdirSync(sourceImagesDir);
  for (const img of images) {
    const src = path.join(sourceImagesDir, img);
    const dest = path.join(publicImagesDir, img);
    fs.copyFileSync(src, dest);
  }
  console.log(`✓ Copied ${images.length} documentation assets to public/images/`);
}

// 2. Read docs.json to get canonical navigation structure
const docsConfigPath = path.join(docsDir, 'docs.json');
if (!fs.existsSync(docsConfigPath)) {
  console.error('docs.json not found in', docsDir);
  process.exit(1);
}

const docsConfig = JSON.parse(fs.readFileSync(docsConfigPath, 'utf8'));
const groups = docsConfig.navigation?.groups || [];

function parseFrontmatterAndHeadings(content) {
  let title = '';
  let description = '';
  let body = content;

  // Frontmatter parsing
  if (content.startsWith('---')) {
    const end = content.indexOf('---', 3);
    if (end !== -1) {
      const frontmatter = content.slice(3, end).trim();
      body = content.slice(end + 3).trim();

      const titleMatch = frontmatter.match(/^title:\s*["']?(.*?)["']?$/m);
      if (titleMatch) title = titleMatch[1].trim();

      const descMatch = frontmatter.match(/^description:\s*["']?(.*?)["']?$/m);
      if (descMatch) description = descMatch[1].trim();
    }
  }

  // If title was not in frontmatter, find first h1
  if (!title) {
    const h1Match = body.match(/^#\s+(.+)$/m);
    if (h1Match) {
      title = h1Match[1].trim();
    }
  }

  // Extract headings for Table of Contents
  const normalizedBody = body.replace(/\r\n/g, '\n');
  const headings = [];
  const lines = normalizedBody.split('\n');
  for (const line of lines) {
    const trimmedLine = line.trim();
    const h2Match = trimmedLine.match(/^##\s+(.+)$/);
    if (h2Match) {
      const text = h2Match[1].replace(/<[^>]*>/g, '').trim();
      const id = text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
      headings.push({ level: 2, text, id });
      continue;
    }
    const h3Match = trimmedLine.match(/^###\s+(.+)$/);
    if (h3Match) {
      const text = h3Match[1].replace(/<[^>]*>/g, '').trim();
      const id = text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
      headings.push({ level: 3, text, id });
    }
  }

  return { title, description, body: normalizedBody, headings };
}

const docPages = [];
const groupNav = [];

for (const group of groups) {
  const groupPages = [];

  for (const pagePath of group.pages) {
    let fullPath = path.join(docsDir, `${pagePath}.mdx`);
    if (!fs.existsSync(fullPath)) {
      fullPath = path.join(docsDir, `${pagePath}.md`);
    }

    if (!fs.existsSync(fullPath)) {
      console.warn(`Warning: file not found for ${pagePath}`);
      continue;
    }

    const rawContent = fs.readFileSync(fullPath, 'utf8');
    const { title, description, body, headings } = parseFrontmatterAndHeadings(rawContent);

    const slug = pagePath;
    const pageItem = {
      slug,
      group: group.group,
      title: title || path.basename(pagePath),
      description: description || '',
      content: body,
      headings,
    };

    docPages.push(pageItem);
    groupPages.push({
      slug,
      title: pageItem.title,
      description: pageItem.description,
    });
  }

  groupNav.push({
    group: group.group,
    pages: groupPages,
  });
}

const fileContent = `// Auto-generated by scripts/build-docs-data.mjs - DO NOT EDIT DIRECTLY
export interface DocHeading {
  level: number;
  text: string;
  id: string;
}

export interface DocPage {
  slug: string;
  group: string;
  title: string;
  description: string;
  content: string;
  headings: DocHeading[];
}

export interface DocGroupNav {
  group: string;
  pages: Array<{
    slug: string;
    title: string;
    description: string;
  }>;
}

export const DOCS_GROUPS: DocGroupNav[] = ${JSON.stringify(groupNav, null, 2)};

export const DOCS_PAGES: Record<string, DocPage> = ${JSON.stringify(
  docPages.reduce((acc, p) => {
    acc[p.slug] = p;
    return acc;
  }, {}),
  null,
  2
)};

export const DOCS_SLUGS: string[] = ${JSON.stringify(docPages.map((p) => p.slug), null, 2)};
`;

fs.writeFileSync(outputDataFile, fileContent, 'utf8');
console.log(`✓ Generated ${outputDataFile} with ${docPages.length} documentation pages across ${groupNav.length} groups.`);
